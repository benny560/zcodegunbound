// 完整复现 calcTimePhysicsSolver 对 N4 left sd=33 wa=90 ws=12 elev=0 的计算
const G=430,MASS=0.23,PF=0.004332712,sdParts=20;
const side='left',spinN=4,distance=33,windAngle=90,windStrength=12,elevationInternal=0;
const sd=Math.abs(distance);
const fits={'left:4':{a:4.8190,b:-0.0180}};
const fit=fits['left:4'];
const windRad=windAngle*Math.PI/180;
const cosW=Math.cos(windRad),sinW=Math.sin(windRad);
const ws=Math.max(0,windStrength||0);
const force=ws===0?0:(Math.abs(cosW+1)<0.001?ws:Math.max(0,ws-1));
const xA=cosW*force/MASS;
const effGrav=G-sinW*force/MASS;
const wy_acc=sinW*force/MASS;
const dT=0.0243-0.00066*wy_acc;
const T_base=fit.a+fit.b*sd;
const G_base=G; // N4: G_base=G
const T_target=T_base+dT;
const xDist=sd*(800/sdParts);
const effGravCalc=G_base-sinW*force/MASS;
const halfEffG_T2=0.5*effGravCalc*T_target*T_target;
const half_xA_T2=0.5*xA*T_target*T_target;
const denom=xDist-half_xA_T2;
const elev=elevationInternal;
const tanA=(elev+halfEffG_T2)/denom;
const angleRaw=Math.atan(tanA)*180/Math.PI;
const cosA=Math.cos(angleRaw*Math.PI/180);
const V=denom/(cosA*T_target);
const power=V*PF;

console.log('=== N4 left sd=33 wa=90 ws=12 elev=0 完整计算过程 ===');
console.log('');
console.log('【第1步: 风参数】');
console.log(`  windAngle=${windAngle}°, cosW=${cosW.toFixed(4)}, sinW=${sinW.toFixed(4)}`);
console.log(`  windStrength=${ws}, force=max(0,ws-1)=${force}`);
console.log(`  xA = cosW·force/MASS = ${cosW.toFixed(4)}·${force}/${MASS} = ${xA.toFixed(4)}`);
console.log(`  wy_acc = sinW·force/MASS = ${sinW.toFixed(4)}·${force}/${MASS} = ${wy_acc.toFixed(4)}`);
console.log(`  effGrav = G - sinW·force/MASS = ${G} - ${wy_acc.toFixed(4)} = ${effGrav.toFixed(4)}`);
console.log('');
console.log('【第2步: 时间T】');
console.log(`  T_base = fit.a + fit.b·sd = ${fit.a} + (${fit.b})·${sd} = ${T_base.toFixed(4)}`);
console.log(`  dT = 0.0243 - 0.00066·wy_acc = 0.0243 - 0.00066·${wy_acc.toFixed(4)} = ${dT.toFixed(4)}`);
console.log(`  T_target = T_base + dT = ${T_base.toFixed(4)} + ${dT.toFixed(4)} = ${T_target.toFixed(4)}`);
console.log('');
console.log('【第3步: 落点约束】');
console.log(`  xDist = sd·(800/sdParts) = ${sd}·${800/sdParts} = ${xDist.toFixed(1)}`);
console.log(`  effGravCalc = G_base - sinW·force/MASS = ${effGravCalc.toFixed(4)}`);
console.log(`  halfEffG·T² = 0.5·${effGravCalc.toFixed(2)}·${T_target.toFixed(3)}² = ${halfEffG_T2.toFixed(2)}`);
console.log(`  half_xA·T² = 0.5·${xA.toFixed(4)}·${T_target.toFixed(3)}² = ${half_xA_T2.toFixed(2)}`);
console.log(`  denom = xDist - half_xA·T² = ${xDist.toFixed(1)} - ${half_xA_T2.toFixed(2)} = ${denom.toFixed(2)}`);
console.log('');
console.log('【第4步: 解角度】');
console.log(`  tanA = (elev + halfEffG·T²)/denom = (${elev} + ${halfEffG_T2.toFixed(2)})/${denom.toFixed(2)} = ${tanA.toFixed(4)}`);
console.log(`  angleRaw = atan(${tanA.toFixed(4)}) = ${angleRaw.toFixed(4)}°`);
console.log('');
console.log('【第5步: 解速度/力度】');
console.log(`  cosA = cos(${angleRaw.toFixed(2)}°) = ${cosA.toFixed(6)}`);
console.log(`  V = denom/(cosA·T) = ${denom.toFixed(2)}/(${cosA.toFixed(6)}·${T_target.toFixed(3)}) = ${V.toFixed(2)}`);
console.log(`  power = V·PF = ${V.toFixed(2)}·${PF} = ${power.toFixed(4)}`);
console.log('');
console.log('=== 最终结果 ===');
console.log(`  angle=${angleRaw.toFixed(2)}° power=${power.toFixed(4)} T=${T_target.toFixed(4)}`);
console.log('');
console.log('=== 关键检查 ===');
console.log(`  xA=${xA.toFixed(4)} (侧风, 水平风分量≈0, 不影响落点)`);
console.log(`  wy_acc=${wy_acc.toFixed(4)} (纯上风, effGrav减小=${effGrav.toFixed(2)}<430)`);
console.log(`  effGrav减小 -> 球飞更久, T_base=${T_base.toFixed(3)} + dT(上风+0.012)=${T_target.toFixed(3)}`);
console.log(`  这T是否合理? N4需要转4圈, T≈4.2s. power=${power.toFixed(4)}`);
