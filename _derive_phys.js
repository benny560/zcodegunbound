// 物理推导: 有水平风时, T该是多少?
//
// 抛物线运动:
//   x(T) = vx*T + 0.5*xA*T^2 = xDist   ...(1) 水平落点
//   y(T) = vy*T - 0.5*g_eff*T^2 = elev  ...(2) 垂直落点
//
// 经典无风时: vx=V*cosA, vy=V*sinA, T=2*vy/g_eff (从y方程, elev=0)
// 有水平风时, y方程不变(风水平不影响垂直), 所以 T 仍由 y方程定!
//   T = 2*vy/g_eff  (平地elev=0)
//   vy = V*sinA, V=power/PF
//
// 所以: 飞行时间T 由【发射的垂直速度vy】决定, 不直接由风决定.
// 水平风xA改变的是: 要落在xDist, vx要满足 (1).
//   vx = (xDist - 0.5*xA*T^2) / T
// 顺风(xA>0): 0.5*xA*T^2 占比增大 => vx要更小 => 角度更高
//   这是物理正确的! 不是T要缩, 是【角度要升高、vx要降】来抵消风的推送.
//
// 那为什么版本A要缩T? 因为T_base+dT是从【实测拟合】来的,
// 它拟合的是"实测角度/力度对应的T". 实测时玩家为了打顺风, 确实用了更陡角度(更小vx),
// 对应的vy更大, T=2*vy/g_eff 反而【更大】! 
// 所以顺风实测T应该更大, 不是更小!
//
// 验证: 图片场景 wa=338(下风为主) T_true=3.90 > T_base=3.92? 接近.
// 但纯顺风 wa=0: 球要高抛让风推, T应该比无风更大.
//
// 关键矛盾: T_base+dT > T_max(denom=0), 说明模型T太大, 但物理上顺风T确实大.
// 那denom<0说明什么? 说明【在这个T下, 即使vx=0(90度), 风也能把球吹过目标】.
// 即 0.5*xA*T^2 > xDist.
// 这在物理上意味着: 目标太近、风太大, 球即使垂直上抛也会被风吹过.
// => 这种情况确实需要【缩短T】(减小vy=减小力度), 牺牲旋转圈数来打近目标.
//
// 所以正确的解: 顺风大风近距离, T必须 < T_base(因为打不出去那么久),
// 但这个T不是由旋转定, 而是由"denom>0"的物理约束定: T < T_max.
// 在 T < T_max 范围内, T应该取【能让旋转最接近N圈】的值.
//
// 简化: 退化情况下, T取 T_max(贴着denom>0的边界), 解出最高角度.
